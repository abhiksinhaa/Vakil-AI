export type DynamicFieldType = 'text' | 'textarea' | 'number' | 'date' | 'select';

export type DynamicField = {
  id: string;
  label: string;
  type: DynamicFieldType;
  required?: boolean;
  placeholder?: string;
  options?: string[];
  showWhen?: { fieldId: string; value: string };
};

export type DynamicDocumentDefinition = {
  key: string;
  name: string;
  category: string;
  purpose: string;
  courtFiling?: boolean;
  baselineTypeKey?: string;
  schemaName?: string;
  catalogueNames: string[];
  fields: DynamicField[];
  templateSections: string[];
  geminiInstructions: string;
};

const f = (
  id: string,
  label: string,
  required = false,
  type: DynamicFieldType = 'textarea',
  options?: string[],
  showWhen?: DynamicField['showWhen'],
): DynamicField => ({
  id,
  label,
  required,
  type,
  ...(type === 'text' ? { placeholder: 'Enter details' } : {}),
  ...(options ? { options } : {}),
  ...(showWhen ? { showWhen } : {}),
});

