export function normalizeDocumentName(value: string): string {
  return value
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ');
}

export function getDynamicDocument(key: string): DynamicDocumentDefinition | undefined {
  return DYNAMIC_DOCUMENTS.find((document) => document.key === key);
}

export function getDynamicDocumentForCatalogueName(name: string): DynamicDocumentDefinition | undefined {
  const normalized = normalizeDocumentName(name);
  return DYNAMIC_DOCUMENTS.find((document) =>
    [document.name, ...document.catalogueNames].some((candidate) =>
      normalizeDocumentName(candidate) === normalized,
    ),
  );
}
